"""Generate TypeScript types from the drf-spectacular OpenAPI schema.

Writes:
  - one `interface` per component schema (refs resolved, enums as literal unions)
  - an `API_ENDPOINTS` list (method/path/tag) for typed client routing

Usage (inside the api container):
  python scripts/generate_shared_types.py --out /app/generated/api.ts

The generated file is committed to packages/shared-types/api.ts (see CI).
"""

import json
import sys
from pathlib import Path

# Allow running as a plain script (python scripts/generate_shared_types.py).
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import os  # noqa: E402

import django  # noqa: E402

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings.dev")
django.setup()

from drf_spectacular.generators import SchemaGenerator  # noqa: E402


def resolve_ref(ref: str) -> str:
    return ref.split("/")[-1]


def ts_type_of(schema: dict, nullable: bool) -> str:
    """Map an OpenAPI schema node to a TypeScript type expression."""
    parts: list[str] = []
    if "$ref" in schema:
        parts.append(schema_to_name(schema["$ref"]))
    elif "enum" in schema:
        literals = " | ".join(json.dumps(value) for value in schema["enum"])
        parts.append(literals)
    else:
        # drf-spectacular wraps $ref/enum nodes in allOf/anyOf/oneOf for
        # nullable fields and SerializerMethodFields — descend into the first
        # meaningful subschema instead of emitting `unknown`.
        for key in ("allOf", "anyOf", "oneOf"):
            subschemas = schema.get(key)
            if subschemas:
                best = next(
                    (s for s in subschemas if "$ref" in s or "enum" in s or s.get("type")),
                    subschemas[0],
                )
                return ts_type_of(best, nullable)
        kind = schema.get("type")
        if kind == "string":
            parts.append("string")
        elif kind == "integer":
            parts.append("number")
        elif kind == "number":
            parts.append("number")
        elif kind == "boolean":
            parts.append("boolean")
        elif kind == "array":
            parts.append(f"Array<{ts_type_of(schema.get('items', {}), False)}>")
        elif kind == "object":
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                parts.append(f"Record<string, {ts_type_of(extra, False)}>")
            else:
                parts.append("Record<string, unknown>")
        else:  # free-form / unspecified
            parts.append("unknown")
    if nullable:
        parts.append("null")
    return " | ".join(parts) if parts else "unknown"


def schema_to_name(ref: str) -> str:
    name = resolve_ref(ref)
    return name.replace("Nullable", "").replace(".", "__")


def render_enum(name: str, schema: dict) -> str:
    literals = " | ".join(json.dumps(value) for value in schema["enum"])
    return f"export type {name} = {literals};"


def render_interface(name: str, schema: dict) -> str:
    properties = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, prop_schema in properties.items():
        nullable = prop_schema.get("nullable", False)
        optional = "" if prop in required else "?"
        ts_type = ts_type_of(prop_schema, nullable)
        safe_prop = f'"{prop}"' if not prop.isidentifier() else prop
        lines.append(f"  {safe_prop}{optional}: {ts_type};")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True, help="Output .ts file path")
    args = parser.parse_args()

    schema = SchemaGenerator().get_schema(public=True)
    components = schema.get("components", {}).get("schemas", {})

    out: list[str] = [
        "// Generated by apps/api/scripts/generate_shared_types.py -- do not edit.",
        "// Source of truth: the drf-spectacular schema of the Blasa API.",
        "",
    ]
    for name in sorted(components):
        component = components[name]
        if component.get("enum"):
            out.append(render_enum(name, component))
        elif component.get("properties") or component.get("type") == "object":
            out.append(render_interface(name, component))
        else:  # bare scalar/anyOf component -> type alias
            out.append(f"export type {name} = {ts_type_of(component, component.get('nullable', False))};")
        out.append("")

    # Typed endpoint catalog for the mobile/web clients.
    endpoints: list[str] = []
    for path, operations in sorted(schema.get("paths", {}).items()):
        for method, operation in operations.items():
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            tag = (operation.get("tags") or ["api"])[0]
            endpoints.append(
                f'  {{ method: "{method.upper()}", path: "{path}", tag: "{tag}", '
                f'operationId: "{operation.get("operationId", "")}" }},'
            )
    out.append("export type ApiMethod = \"GET\" | \"POST\" | \"PUT\" | \"PATCH\" | \"DELETE\";")
    out.append("")
    out.append("export interface ApiEndpointInfo {")
    out.append("  method: ApiMethod;")
    out.append("  path: string;")
    out.append("  tag: string;")
    out.append("  operationId: string;")
    out.append("}")
    out.append("")
    out.append("export const API_ENDPOINTS: ApiEndpointInfo[] = [")
    out.extend(endpoints)
    out.append("];")
    out.append("")

    destination = Path(args.out)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {destination} ({len(components)} interfaces, {len(endpoints)} endpoints)")


if __name__ == "__main__":
    main()
